# ---------------------- MFA Utility Functions ----------------------
def generate_mfa_secret():
    """Generate a 16-bit Base32 secret key compliant with TOTP standards"""
    return pyotp.random_base32()

def generate_mfa_qr_code(secret, email):
    """Generate MFA binding QR code (returns Base64 encoding)"""
    totp_uri = pyotp.totp.TOTP(secret).provisioning_uri(
        name=email,
        issuer_name="ElectionOfficerSystem"
    )
    qr = qrcode.QRCode(version=1, box_size=10, border=4)
    qr.add_data(totp_uri)
    qr.make(fit=True)
    img = qr.make_image(fill_color="black", back_color="white")
    buffer = BytesIO()
    img.save(buffer, format="PNG")
    return base64.b64encode(buffer.getvalue()).decode('utf-8')

def verify_mfa_code(secret, code):
    """Verify MFA verification code (allows ±30 seconds error)"""
    totp = pyotp.TOTP(secret)
    return totp.verify(code, valid_window=1)

