@app.route('/setup_mfa', methods=['GET', 'POST'])
def setup_mfa():
    """MFA setup page (for first login without MFA)"""
    if 'temp_officer_id' not in session or 'temp_mfa_secret' not in session:
        flash("Please log in first", 'error')
        return redirect(url_for('elec_officer_login'))
    
    mfa_secret = session['temp_mfa_secret']
    officer_email = session.get('temp_officer_email', 'officer@example.com')
    
    if request.method == 'POST':
        mfa_code = request.form['mfa_code'].strip()
        if verify_mfa_code(mfa_secret, mfa_code):
            # Save MFA secret and enable MFA
            conn = None
            try:
                conn = get_db_connection()
                cursor = conn.cursor()
                cursor.execute("""
                    UPDATE elec_officers 
                    SET mfa_secret = %s, mfa_enabled = TRUE 
                    WHERE id = %s
                """, (mfa_secret, session['temp_officer_id']))
                conn.commit()
                # Create official session
                session['elec_officer_id'] = session['temp_officer_id']
                session['elec_officer_name'] = session['temp_officer_name']
                # Clear temporary data
                session.pop('temp_officer_id', None)
                session.pop('temp_officer_name', None)
                session.pop('temp_mfa_secret', None)
                session.pop('temp_officer_email', None)
                log_audit(session['elec_officer_id'], 'mfa_setup_success', request.remote_addr, "Completed MFA setup")
                flash("MFA setup successful! You are now logged in.", 'message')
                return redirect(url_for('index'))
            except Exception as e:
                log_audit(session['temp_officer_id'], 'mfa_setup_failed', request.remote_addr, str(e))
                flash(f"Failed to set up MFA: {e}", 'error')
                return redirect(url_for('elec_officer_login'))
            finally:
                if conn:
                    conn.close()
        else:
            flash("Invalid verification code. Please try again.", 'error')
    
    # Generate QR code for GET request
    qr_code_base64 = generate_mfa_qr_code(mfa_secret, officer_email)
    return render_template_string(
        MFA_SETUP_TEMPLATE,
        mfa_secret=mfa_secret,
        qr_code_base64=qr_code_base64
    )

