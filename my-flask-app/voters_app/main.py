def init_db():
    conn = None
    try:
        conn = get_db_connection()
        cursor = conn.cursor()
        # Update elec_officers table: add MFA fields
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS elec_officers (
                id INT AUTO_INCREMENT PRIMARY KEY,
                name VARCHAR(255) NOT NULL,
                email VARCHAR(255) NOT NULL UNIQUE,
                password VARCHAR(255) NOT NULL,
                role ENUM('elec_officer') DEFAULT 'elec_officer',
                mfa_secret VARCHAR(255) NULL,  -- Store MFA secret
                mfa_enabled BOOLEAN DEFAULT FALSE  -- MFA enabled flag
            );
        """)
        # Update voters table (add age/sex if not exist)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS voters (
                id INT AUTO_INCREMENT PRIMARY KEY,
                name VARCHAR(255) NOT NULL,
                email VARCHAR(255) NOT NULL UNIQUE,
                status ENUM('submitted', 'accepted', 'rejected') DEFAULT 'submitted'
            );
        """)
        cursor.execute("SHOW COLUMNS FROM voters LIKE 'age'")
        if not cursor.fetchone():
            cursor.execute("ALTER TABLE voters ADD COLUMN age INT NOT NULL DEFAULT 18")
        cursor.execute("SHOW COLUMNS FROM voters LIKE 'sex'")
        if not cursor.fetchone():
            cursor.execute("ALTER TABLE voters ADD COLUMN sex ENUM('Male', 'Female', 'Other') NOT NULL DEFAULT 'Other'")
        # Update audit_logs table (keep existing)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS audit_logs (
                id INT AUTO_INCREMENT PRIMARY KEY,
                user_id INT,
                action VARCHAR(255),
                timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                ip VARCHAR(45),
                details TEXT
            );
        """)
        # Add MFA fields to existing elec_officers table (if missing)
        cursor.execute("SHOW COLUMNS FROM elec_officers LIKE 'mfa_secret'")
        if not cursor.fetchone():
            cursor.execute("ALTER TABLE elec_officers ADD COLUMN mfa_secret VARCHAR(255) NULL")
        cursor.execute("SHOW COLUMNS FROM elec_officers LIKE 'mfa_enabled'")
        if not cursor.fetchone():
            cursor.execute("ALTER TABLE elec_officers ADD COLUMN mfa_enabled BOOLEAN DEFAULT FALSE")
        
        conn.commit()
        print("Database initialized successfully (MFA fields added to elec_officers)")
    except Exception as e:
        print(f"Error initializing database: {e}")
    finally:
        if conn:
            conn.close()

